_CANONICAL_GUARD={code:code for code in GUARD_CODES}
REASONS=frozenset(('GUARD_BLOCKED','UNEXPECTED_EXCEPTION',*_CLASSES.values(),*GUARD_CODES))
FIELDS=frozenset(('failure_stage','failure_operation','failure_errno','reason'))

def describe(error,stage):
    phase=stage if type(stage) is str and stage in PHASES else 'unknown'
    operation='unknown';trace=error.__traceback__
    while trace is not None:
        frame=trace.tb_frame
        key=(frame.f_globals.get('__name__'),frame.f_code.co_name)
        if key in _OPERATIONS:operation=_OPERATIONS[key]
        trace=trace.tb_next
    number=error.errno if isinstance(error,OSError) else None
    if type(number) is not int or number not in errno.errorcode:number=None
    reason=_CLASSES.get(type(error),'UNEXPECTED_EXCEPTION')
    if isinstance(error,Blocked):
        value=error.args[0] if error.args and type(error.args[0]) is str else ''
        reason=_CANONICAL_GUARD.get(value.split(':',1)[0],'GUARD_BLOCKED')
    return dict(failure_stage=phase,failure_operation=operation,failure_errno=number,reason=reason)

def validate_public_failure(facts):
    """Strict opt-in failure metadata schema for the independent upload guard."""
    if facts.get('status') in ('BLOCKED','cleanup-failed') and set(facts)-FIELDS-{'status','scope','runtime_pass','capture_started','permissions_granted','cleanup_errors','teardownVerified'}:
        raise ValueError('FAILURE_EXTRA_FIELDS')
    present=FIELDS & set(facts)
    if not present:return  # Cleanup-only failures may have no originating exception metadata.
    if present!=FIELDS:raise ValueError('FAILURE_METADATA_INCOMPLETE')
    if type(facts['failure_stage']) is not str or facts['failure_stage'] not in PHASES:raise ValueError('FAILURE_STAGE_UNKNOWN')
    if type(facts['failure_operation']) is not str or facts['failure_operation'] not in OPERATIONS:raise ValueError('FAILURE_OPERATION_UNKNOWN')
    if type(facts['reason']) is not str or facts['reason'] not in REASONS:raise ValueError('FAILURE_REASON_UNKNOWN')
    number=facts['failure_errno']
    if number is not None and (type(number) is not int or number not in errno.errorcode):raise ValueError('FAILURE_ERRNO_UNKNOWN')
    if facts.get('status') not in ('BLOCKED','cleanup-failed'):raise ValueError('FAILURE_METADATA_WITHOUT_FAILURE')
